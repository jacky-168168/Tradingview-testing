"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const {validate,ORDER,priceCls}=require("../docs/tdcc-whale-weekly.js");
assert.deepEqual(ORDER,["續買","回頭車","下車","續賣"]);
const groups=Object.fromEntries(ORDER.map(k=>[k,{count:0,rows:[],priceCount:0,avgPriceReturnPct:null,upCount:0}]));
const row={code:"6278",name:"台表科",previousPP:3.5,currentPP:5.48,bigHolderRatio:74.337,priceReturnPct:20.4};
groups["續買"]={count:1,rows:[row],priceCount:1,upCount:1,avgPriceReturnPct:20.4};
const original={version:"TDCC_WHALE_400_QUADRANTS_V1",date:"2026-10-16",priorDate:"2026-10-08",twoWeeksBefore:"2026-10-02",thresholdPP:1.0,quadrants:groups};
assert.equal(validate(original),original);
assert.throws(()=>validate({...original,date:"2026-10-02"}),/日期|基準日/);
assert.throws(()=>validate({...original,thresholdPP:0}),/格式/);
assert.throws(()=>validate({...original,quadrants:{...groups,"續買":{...groups["續買"],count:3}}}),/數量/);
assert.throws(()=>validate({...original,quadrants:{...groups,"續買":{...groups["續買"],rows:[{...row,currentPP:-1.1}]}}}),/方向/);
assert.equal(priceCls(3),"is-red");
assert.equal(priceCls(-3),"is-green");
assert.equal(priceCls(0),"is-neutral");
const h=fs.readFileSync(path.join(__dirname,"../docs/index.html"),"utf8");
const page=fs.readFileSync(path.join(__dirname,"../docs/tdcc-whale-weekly.html"),"utf8");
assert.match(h,/<nav class="site-nav"/);
assert.match(h,/<a class="btn" href="\.\/tdcc-whale-weekly\.html"[^>]*>🐋 大戶換手週報<\/a>/);
assert.ok(!h.includes('id="tdccWhalePanel"'),"Do not keep the large weekly panel on the homepage");
for(const id of ["tdccWhalePanel","tdccWhaleCards","tdccWhaleStatus","tdccWhaleDates","tdccWhaleCoverage","tdccWhaleFoot","tdccWhaleRetry"])
 assert.ok(page.includes('id="'+id+'"'),"Standalone weekly page missing "+id);
assert.match(page,/tdcc-whale-weekly\.js/);
assert.match(page,/tdcc-whale-weekly\.css/);
assert.match(page,/site-access\.js/);
assert.match(page,/href="\.\/index\.html"/);
assert.ok(page.includes("400張以上")&&page.includes("每週更新"));
console.log("PASS TDCC weekly quadrant data and header-nav standalone report fields.");
