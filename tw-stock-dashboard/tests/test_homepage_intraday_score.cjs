'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const panel=require(path.join(root,'docs/market-command.js'));
const html=fs.readFileSync(path.join(root,'docs/index.html'),'utf8');
const g=JSON.parse(fs.readFileSync(path.join(root,'docs/data/g_intraday/latest.json'),'utf8'));
const observed=new Date(g.publishedAt);
assert.ok(Number.isFinite(observed.getTime()),'publishedAt should be an ISO timestamp');
const now=new Date(observed.getTime()+2*60*1000);
const view=panel.indicativeMarketBreadthScore(g,now);
assert.ok(view,'same-day valid G quote breadth must produce an indicative score');
const values=g.indicativeQuoteBreadth.total;
assert.equal(view.score,Math.round(values.up/values.sample*100));
assert.ok(view.sample>=1000);
assert.ok(/setInterval\(\(\)=>\{const m=localClock\(\)/.test(html),'live market refresh must run independently');
assert.ok(/void loadIntradayMarketBreadth\(\)/.test(html),'market breadth refresh call not present');
assert.equal(panel.indicativeMarketBreadthScore({...g,asOfDate:'2026-10-30'},now),null,'older sessions must not be treated as today');
assert.equal(panel.indicativeMarketBreadthScore(g,new Date(observed.getTime()+66*60*1000)),null,'expired quotes must not produce score');
console.log('PASS current G market breadth shown as '+view.score+'/100 (indicative, not official Risk Score), sample '+view.sample+', published '+g.publishedAt);
